-- Function: get_job_seeker_detail (replaces getJobSeekerDetail raw SQL)
CREATE OR REPLACE FUNCTION get_job_seeker_detail(
    p_gender          text    DEFAULT NULL,
    p_min_experience  integer DEFAULT NULL,
    p_max_experience  integer DEFAULT NULL,
    p_skills          text    DEFAULT NULL
)
RETURNS TABLE(
    id                bigint,
    name              text,
    email             text,
    contact_no        text,
    age               integer,
    gender            text,
    qualification     text,
    experience        text,
    skills            text,
    street            text,
    landmark          text,
    city              text,
    result_count      bigint
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT
        js.id, js.name, js.email, js.contact_no, js.age, js.gender,
        js.qualification, js.experience, js.skills,
        a.street, a.landmark, a.city::text,
        COUNT(*) OVER () AS result_count
    FROM job_seeker js
    LEFT JOIN address a ON js.id = a.parent_id AND a.parent = 'job_seeker'
    WHERE js.status = 'active'
      AND (p_gender IS NULL OR js.gender = p_gender)
      AND (p_min_experience IS NULL OR (CASE WHEN js.experience ~ '^[0-9]+$' THEN js.experience::integer ELSE 0 END) >= p_min_experience)
      AND (p_max_experience IS NULL OR (CASE WHEN js.experience ~ '^[0-9]+$' THEN js.experience::integer ELSE 100 END) <= p_max_experience)
      AND (p_skills IS NULL OR js.skills ILIKE '%' || p_skills || '%')
    ORDER BY js.updated_at DESC;
END;
$$;

-- Function: get_sponsored_products (replaces getSponsored raw SQL)
CREATE OR REPLACE FUNCTION get_sponsored_products()
RETURNS TABLE(
    id               bigint,
    product_id       integer,
    title            text,
    subtitle         text,
    image_src        text,
    price            text,
    discounted_price numeric,
    brand            text,
    product_name     text
)
LANGUAGE sql
SECURITY DEFINER
AS $$
    SELECT
        pa.id, pa.product_id, pa.title, pa.subtitle,
        pi.image_src,
        p.price, p.discounted_price, p.brand,
        p.name AS product_name
    FROM product_ad pa
    JOIN product p ON pa.product_id = p.id
    LEFT JOIN product_image pi ON p.id = pi.parent_id AND pi.priority = 1
    WHERE pa.status = 'active'
      AND pa.start_date <= CURRENT_DATE
      AND pa.end_date >= CURRENT_DATE
    ORDER BY pa.ad_budget DESC;
$$;

-- Function: get_salon_employee (replaces getSalonEmployee raw SQL)
CREATE OR REPLACE FUNCTION get_salon_employee(
    p_salon_code text,
    p_service_id integer DEFAULT NULL
)
RETURNS TABLE(
    id          bigint,
    name        text,
    email       text,
    contact_no  text,
    rating      integer,
    gender      text,
    services    text,
    slots       jsonb
)
LANGUAGE sql
SECURITY DEFINER
AS $$
    SELECT
        se.id, se.name, se.email, se.contact_no, se.rating, se.gender, se.services, se.slots
    FROM salon_employee se
    JOIN salon s ON se.salon_id = s.id
    WHERE s.salon_code = p_salon_code
      AND se.status = 'active'
      AND (p_service_id IS NULL OR se.services ILIKE '%' || p_service_id::text || '%');
$$;

-- Function: increment_click_count
CREATE OR REPLACE FUNCTION increment_click_count(row_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    UPDATE product_ad
    SET click_count = click_count + 1,
        updated_at = now()
    WHERE id = row_id;
END;
$$;

