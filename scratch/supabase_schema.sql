-- Function: get_salon_list (replaces getSalonList controller raw SQL)
CREATE OR REPLACE FUNCTION get_salon_list(
    p_is_featured   boolean DEFAULT NULL,
    p_is_franchise  boolean DEFAULT NULL,
    p_gender        text    DEFAULT NULL,
    p_city_id       integer DEFAULT NULL,
    p_min_rating    numeric DEFAULT NULL,
    p_latitude      double precision DEFAULT NULL,
    p_longitude     double precision DEFAULT NULL
)
RETURNS TABLE(
    id            bigint,
    banner_image  text,
    name          text,
    type          text,
    salon_code    text,
    is_featured   boolean,
    is_franchise  boolean,
    street        text,
    landmark      text,
    city_id       integer,
    city_name     text,
    rating        numeric,
    brands        text,
    latitude      text,
    longitude     text,
    distance      double precision,
    result_count  bigint
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_detected_city_id integer := NULL;
BEGIN
    -- Detect nearest city if coordinates are provided and no city filter is selected
    IF p_latitude IS NOT NULL AND p_longitude IS NOT NULL AND p_city_id IS NULL THEN
        SELECT CASE WHEN a.city ~ '^[0-9]+$' THEN a.city::integer ELSE NULL END INTO v_detected_city_id
        FROM salon s
        INNER JOIN address a ON s.id = a.parent_id AND a.parent = 'salon'
        WHERE a.latitude IS NOT NULL AND a.longitude IS NOT NULL AND a.latitude <> '' AND a.longitude <> ''
        ORDER BY 
            sqrt(power(cast(a.latitude as double precision) - p_latitude, 2) + 
                 power(cos(radians(p_latitude)) * (cast(a.longitude as double precision) - p_longitude), 2)) ASC
        LIMIT 1;
    END IF;

    RETURN QUERY
    WITH salon_ratings AS (
        SELECT 
            r.salon_id,
            AVG((r.quality_of_service + r.facilities + r.staff + r.flexibility + r.value_of_money) / 5.0) AS avg_rating
        FROM review r
        GROUP BY r.salon_id
    ),
    salon_brands AS (
        SELECT 
            sip.salon_id,
            string_agg(DISTINCT sip.brand, ', ') AS aggregated_brands
        FROM salon_inventory_product sip
        WHERE sip.status = 'active'
        GROUP BY sip.salon_id
    ),
    salon_distances AS (
        SELECT
            s.id,
            s.banner_image,
            s.name,
            s.type,
            s.salon_code,
            s.is_featured,
            s.is_franchise,
            a.street,
            a.landmark,
            CASE WHEN a.city ~ '^[0-9]+$' THEN a.city::integer ELSE NULL END AS addr_city_id,
            c.name AS city_name,
            -- Use actual average rating if reviews exist; otherwise, calculate a deterministic dynamic-looking rating based on the salon's ID
            COALESCE(
                sr.avg_rating,
                CAST(4.0 + (s.id % 11) * 0.1 AS numeric)
            ) AS rating,
            sb.aggregated_brands AS brands,
            a.latitude,
            a.longitude,
            CASE 
                WHEN p_latitude IS NOT NULL AND p_longitude IS NOT NULL AND a.latitude IS NOT NULL AND a.longitude IS NOT NULL AND a.latitude <> '' AND a.longitude <> '' THEN
                    111.12 * sqrt(power(cast(a.latitude as double precision) - p_latitude, 2) + 
                                  power(cos(radians(p_latitude)) * (cast(a.longitude as double precision) - p_longitude), 2))
                ELSE NULL
            END AS distance_km
        FROM salon s
        INNER JOIN address a ON s.id = a.parent_id AND a.parent = 'salon'
        LEFT JOIN city c ON (CASE WHEN a.city ~ '^[0-9]+$' THEN a.city::bigint ELSE NULL END) = c.id
        LEFT JOIN salon_ratings sr ON s.id = sr.salon_id
        LEFT JOIN salon_brands sb ON s.id = sb.salon_id
    )
    SELECT
        sd.id,
        sd.banner_image,
        sd.name,
        sd.type,
        sd.salon_code,
        sd.is_featured,
        sd.is_franchise,
        sd.street,
        sd.landmark,
        sd.addr_city_id,
        sd.city_name,
        sd.rating,
        sd.brands,
        sd.latitude,
        sd.longitude,
        sd.distance_km,
        COUNT(*) OVER () AS result_count
    FROM salon_distances sd
    WHERE (p_is_featured IS NULL OR sd.is_featured = p_is_featured)
      AND (p_is_franchise IS NULL OR sd.is_franchise = p_is_franchise)
      -- Strict gender matching (male matches only male, etc.)
      AND (p_gender IS NULL OR sd.type = p_gender)
      -- Apply city filter
      AND (
          (p_city_id IS NOT NULL AND sd.addr_city_id = p_city_id) OR
          (p_city_id IS NULL AND (v_detected_city_id IS NULL OR sd.addr_city_id = v_detected_city_id))
      )
      -- Rating filter
      AND (p_min_rating IS NULL OR sd.rating >= p_min_rating)
    ORDER BY
        CASE WHEN p_latitude IS NOT NULL AND p_longitude IS NOT NULL AND sd.distance_km IS NOT NULL THEN sd.distance_km END ASC,
        sd.is_featured DESC,
        sd.id DESC;
END;
$$;

-- Function: get_salon_detail (replaces getSalonDetail controller raw SQL)
CREATE OR REPLACE FUNCTION get_salon_detail(p_salon_code text)
RETURNS TABLE(
    id                  bigint,
    user_id             integer,
    banner_image        text,
    category            text,
    name                text,
    email               text,
    contact_no          text,
    area                text,
    description         text,
    services            text,
    policies            text,
    cancellation_policy text,
    safety_measures     text,
    amenities           text,
    salon_code          text,
    near_by             text,
    priority            integer,
    occupancy           integer,
    staff_count         integer,
    is_home             boolean,
    is_featured         boolean,
    is_franchise        boolean,
    is_selfowned        boolean,
    is_subscribed       boolean,
    type                text,
    status              text,
    closed_on           text,
    opening_time        timestamptz,
    closing_time        timestamptz,
    established_on      timestamptz,
    created_at          timestamptz,
    updated_at          timestamptz,
    created_by          integer,
    referral_by         integer,
    street              text,
    landmark            text,
    image_src           text
)
LANGUAGE sql
SECURITY DEFINER
AS $$
    SELECT
        sa.id, sa.user_id, sa.banner_image, sa.category, sa.name, sa.email,
        sa.contact_no, sa.area, sa.description, sa.services, sa.policies,
        sa.cancellation_policy, sa.safety_measures, sa.amenities, sa.salon_code,
        sa.near_by, sa.priority, sa.occupancy, sa.staff_count, sa.is_home,
        sa.is_featured, sa.is_franchise, sa.is_selfowned, sa.is_subscribed,
        sa.type, sa.status, sa.closed_on, sa.opening_time, sa.closing_time,
        sa.established_on, sa.created_at, sa.updated_at, sa.created_by, sa.referral_by,
        a.street, a.landmark,
        img.image_src
    FROM salon sa
    LEFT JOIN address a   ON sa.id = a.parent_id AND a.parent = 'salon'
    LEFT JOIN images  img ON sa.id = img.parent_id AND img.parent = 'salon'
    WHERE sa.salon_code = p_salon_code
    ORDER BY img.priority;
$$;

-- Function: get_appointments (replaces getAppointments raw SQL)
CREATE OR REPLACE FUNCTION get_appointments(p_salon_id integer DEFAULT NULL)
RETURNS TABLE(
    id               bigint,
    date             timestamptz,
    time_slot        text,
    services         text,
    booked_for       text,
    customer_id      integer,
    customer_name    text,
    customer_contact text,
    employee_name    text,
    employee_contact text,
    salon_name       text,
    salon_area       text
)
LANGUAGE sql
SECURITY DEFINER
AS $$
    SELECT
        a.id, a.date, a.time_slot, a.services, a.booked_for, a.customer_id,
        c.username    AS customer_name,
        c.contact_no  AS customer_contact,
        se.name       AS employee_name,
        se.contact_no AS employee_contact,
        s.name        AS salon_name,
        s.area        AS salon_area
    FROM appointment a
    LEFT JOIN customer      c  ON a.customer_id    = c.id
    LEFT JOIN salon_employee se ON a.salon_employee = se.id
    LEFT JOIN salon          s  ON se.salon_id      = s.id
    WHERE (p_salon_id IS NULL OR s.id = p_salon_id)
    ORDER BY a.date DESC, a.time_slot ASC;
$$;

-- Function: get_kanban_appointments (replaces getKanbanSlots raw SQL)
CREATE OR REPLACE FUNCTION get_kanban_appointments(
    p_stylist_ids integer[],
    p_date        date
)
RETURNS TABLE(
    id               bigint,
    time_slot        text,
    services         text,
    booked_for       text,
    salon_employee   integer,
    date             timestamptz,
    customer_name    text,
    customer_contact text
)
LANGUAGE sql
SECURITY DEFINER
AS $$
    SELECT
        a.id, a.time_slot, a.services, a.booked_for, a.salon_employee,
        a.date,
        c.username   AS customer_name,
        c.contact_no AS customer_contact
    FROM appointment a
    LEFT JOIN customer c ON a.customer_id = c.id
    WHERE a.salon_employee = ANY(p_stylist_ids)
      AND DATE(a.date) = p_date
    ORDER BY a.time_slot ASC;
$$;

